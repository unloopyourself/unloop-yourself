export function pickUnlockPhrase(
  locale: LocaleCode,
  random: () => number = Math.random,
): string {
  const pack = UNLOCK_PHRASES[locale] ?? UNLOCK_PHRASES.en;
  const idx = Math.floor(random() * pack.length);
  return pack[idx] ?? pack[0]!;
}
